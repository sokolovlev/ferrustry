//! Отчёт о балансе: кривая сложности из настоящих прогонов симуляции (`ferrustry-headless balance`).

use std::fmt::Write as _;

use ferrustry_content::ContentRegistry;
use ferrustry_sim::balance::{self, Defense};
use ferrustry_sim::mapgen::{Difficulty, STARTER_INGOTS};
use ferrustry_sim::{Rules, TICKS_PER_SECOND};

/// Предел числа турелей в испытании (больше — «не удержать»).
const MAX_TURRETS: u32 = 48;
/// Предел числа производственных ячеек в расчёте.
const MAX_CELLS: u32 = 400;
/// Уровни шума, для которых показано время прихода волны.
const NOISE_LEVELS: [u32; 3] = [0, 30, 75];

fn mmss(ticks: u64) -> String {
    let s = ticks / u64::from(TICKS_PER_SECOND);
    format!("{}:{:02}", s / 60, s % 60)
}

/// Отчёт в Markdown на русском (`en = false`) или английском.
pub fn report(
    reg: &ContentRegistry,
    difficulty: Difficulty,
    waves: u32,
    en: bool,
) -> Result<String, String> {
    let t = |ru: &'static str, eng: &'static str| if en { eng } else { ru };
    let (first, spacing) = difficulty.timing_secs();
    let tps = u64::from(TICKS_PER_SECOND);
    let rules = Rules {
        infinite_resources: false,
        waves: true,
        first_wave: first * tps,
        wave_spacing: spacing * tps,
    };
    let cell = balance::economy_cell(reg).map_err(|e| e.to_string())?;
    let gun_cost: u32 = reg
        .block_by_name("gun_turret")
        .map(|b| reg.block(b).cost.iter().map(|s| s.count).sum())
        .unwrap_or(0);
    let mut s = String::new();
    let w = &mut s;
    let _ = writeln!(
        w,
        "# {}\n",
        t(
            "Отчёт о балансе: кривая сложности",
            "Balance report: difficulty curve"
        )
    );
    let _ = writeln!(
        w,
        "> {} `ferrustry-headless balance --difficulty {} --waves {waves}{}`.\n",
        t("Сгенерировано:", "Generated by:"),
        format!("{difficulty:?}").to_lowercase(),
        if en { " --lang en" } else { "" }
    );
    let _ = writeln!(w, "## {}\n", t("Как считалось", "How it is computed"));
    let _ = writeln!(
        w,
        "{}",
        if en {
            format!(
                "- **Defence trial:** the real wave N (composition from the data, 3 spawn points like a \
                 medium map, ~30 tiles from the core) against K turrets in rings around the core; \
                 ammo is refilled every tick (an uninterrupted belt) and its use is counted. \"Holds\" = \
                 every enemy destroyed and the core takes no damage. The smallest K up to {MAX_TURRETS} is \
                 searched (binary search; spawn randomness can make neighbouring waves differ by a few \
                 turrets). Every trial runs on 3 spawn spreads and must hold in all. Arc towers each get \
                 4 wind turbines on the core side (full power).\n\
                 - **Arrival:** difficulty {difficulty:?} (first wave {}:{:02}, then every {}:{:02}) with \
                 constant noise.\n\
                 - **Production cell** of the megabase (2 bores on ore → smelter on 2 wind turbines → belt): \
                 {} ingots per 10 min, noise {}, costs {} ingots — measured in steady state.\n\
                 - **Cells needed:** the smallest number of cells whose output by the wave's arrival pays \
                 for themselves, for the guns that hold this wave and for all ammo up to it, minus the \
                 {STARTER_INGOTS} starter ingots — and their noise speeds the waves up. Optimistic: \
                 production from the first second, no logistics to the turrets.",
                first / 60,
                first % 60,
                spacing / 60,
                spacing % 60,
                cell.ingots_per_10min,
                cell.noise,
                cell.cost
            )
        } else {
            format!(
                "- **Испытание обороны:** настоящая волна N (состав из данных, 3 точки появления, как на \
                 средней карте, ~30 тайлов до ядра) против K турелей кольцами вокруг ядра; боеприпасы \
                 пополняются каждый тик (бесперебойная лента), расход считается. «Держит» — все враги \
                 уничтожены, ядро без урона. Ищется наименьшее K до {MAX_TURRETS} (двоичный поиск; из-за \
                 случайного разброса появления соседние волны могут отличаться на несколько турелей). \
                 Каждое испытание — на 3 вариантах разброса, держать нужно во всех. Дуговым турелям — по \
                 4 ветряка со стороны ядра (полное питание).\n\
                 - **Приход волны:** сложность {difficulty:?} (первая волна {}:{:02}, затем каждые \
                 {}:{:02}) при постоянном шуме.\n\
                 - **Производственная ячейка** мегабазы (2 бура на руде → плавильня на 2 ветряках → \
                 лента): {} слитков за 10 мин, шум {}, стоит {} слитков — замер в установившемся режиме.\n\
                 - **Нужно ячеек:** наименьшее число ячеек, выработка которых к приходу волны окупает \
                 сами ячейки, пушки, держащие эту волну, и все боеприпасы до неё, за вычетом \
                 {STARTER_INGOTS} стартовых слитков, — при том что их шум ускоряет волны. Оценка \
                 оптимистичная: выработка с первой секунды, без логистики к турелям.",
                first / 60,
                first % 60,
                spacing / 60,
                spacing % 60,
                cell.ingots_per_10min,
                cell.noise,
                cell.cost
            )
        }
    );
    let _ = writeln!(w, "\n## {}\n", t("Кривая", "The curve"));
    let mut head = t(
        "| Волна | Врагов | Пушек | Боеприпасов, слитков | Дуговых |",
        "| Wave | Enemies | Guns | Ammo, ingots | Arcs |",
    )
    .to_owned();
    for n in NOISE_LEVELS {
        if n == 0 {
            head.push_str(t(" Приход (тихо) |", " Arrives (quiet) |"));
        } else {
            let _ = write!(head, "{}{n}) |", t(" Приход (шум ", " Arrives (noise "));
        }
    }
    head.push_str(t(" Нужно ячеек |", " Cells needed |"));
    let _ = writeln!(w, "{head}");
    let _ = writeln!(w, "|{}", "---|".repeat(6 + NOISE_LEVELS.len()));
    let (mut ammo_total, mut guns_fail, mut arcs_fail, mut cells_fail) = (0u64, None, None, None);
    let mut prev_guns = 0u32;
    for n in 1..=waves {
        let guns =
            balance::min_defense(reg, n, Defense::Guns, MAX_TURRETS).map_err(|e| e.to_string())?;
        let arcs =
            balance::min_defense(reg, n, Defense::Arcs, MAX_TURRETS).map_err(|e| e.to_string())?;
        let enemies = guns
            .map(|(_, tr)| tr.enemies)
            .or(arcs.map(|(_, tr)| tr.enemies))
            .unwrap_or(0);
        let fmt_k = |k: Option<(u32, balance::Trial)>| {
            k.map_or(format!("> {MAX_TURRETS}"), |(k, _)| k.to_string())
        };
        let mut row = format!("| {n} | {enemies} | {} |", fmt_k(guns));
        let cells = match guns {
            Some((k, tr)) => {
                ammo_total += u64::from(tr.ammo_items);
                prev_guns = prev_guns.max(k);
                let _ = write!(row, " {} |", tr.ammo_items);
                let needed = (u64::from(prev_guns) * u64::from(gun_cost) + ammo_total)
                    .saturating_sub(u64::from(STARTER_INGOTS));
                balance::cells_needed(reg, &rules, &cell, n, needed, MAX_CELLS)
            }
            None => {
                guns_fail.get_or_insert(n);
                row.push_str(" — |");
                None
            }
        };
        if arcs.is_none() {
            arcs_fail.get_or_insert(n);
        }
        let _ = write!(row, " {} |", fmt_k(arcs));
        for noise in NOISE_LEVELS {
            let _ = write!(
                row,
                " {} |",
                mmss(balance::wave_arrival(reg, &rules, n, noise))
            );
        }
        match cells {
            Some(c) => {
                let _ = write!(row, " {c} |");
            }
            None => {
                if guns.is_some() {
                    cells_fail.get_or_insert(n);
                }
                row.push_str(" — |");
            }
        }
        let _ = writeln!(w, "{row}");
    }
    let _ = writeln!(w, "\n## {}\n", t("Выводы", "Findings"));
    let line = |w: &mut String, ru: String, eng: String| {
        let _ = writeln!(w, "- {}", if en { eng } else { ru });
    };
    match guns_fail {
        Some(n) => line(
            w,
            format!("Одними пушками (до {MAX_TURRETS}) не удержать волну {n} и дальше."),
            format!("Guns alone (up to {MAX_TURRETS}) cannot hold wave {n} and later."),
        ),
        None => line(
            w,
            format!("Пушки (до {MAX_TURRETS}) держат все волны до {waves}."),
            format!("Guns (up to {MAX_TURRETS}) hold every wave up to {waves}."),
        ),
    }
    match arcs_fail {
        Some(n) => line(
            w,
            format!("Одними дуговыми турелями (до {MAX_TURRETS}) не удержать волну {n} и дальше."),
            format!("Arc towers alone (up to {MAX_TURRETS}) cannot hold wave {n} and later."),
        ),
        None => line(
            w,
            format!("Дуговые турели (до {MAX_TURRETS}) держат все волны до {waves}."),
            format!("Arc towers (up to {MAX_TURRETS}) hold every wave up to {waves}."),
        ),
    }
    match cells_fail {
        Some(n) => line(
            w,
            format!(
                "С волны {n} экономика не успевает: даже {MAX_CELLS} ячеек (с их шумом) не окупают пушечную оборону к приходу волны."
            ),
            format!(
                "From wave {n} the economy cannot keep up: even {MAX_CELLS} cells (with their noise) do not pay for a gun defence by the wave's arrival."
            ),
        ),
        None => line(
            w,
            "Экономика из производственных ячеек успевает оплатить пушечную оборону ко всем волнам.".into(),
            "An economy of production cells can pay for a gun defence by every wave.".into(),
        ),
    }
    Ok(s)
}
