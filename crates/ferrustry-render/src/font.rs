#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn all_glyphs_are_5x7() {
        for c in CHARSET.chars() {
            let g = glyph(c).unwrap_or_else(|| panic!("missing glyph {c:?}"));
            for row in g {
                assert_eq!(row.len(), GLYPH_W as usize, "glyph {c:?}");
                assert!(row.chars().all(|ch| ch == '#' || ch == '.'));
            }
        }
        assert!(glyph('a').is_some(), "lowercase maps to uppercase");
        assert!(glyph('Ж').is_none());
    }
}
